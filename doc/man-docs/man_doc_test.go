func TestReadManPageClosesFileBeforeWrite(t *testing.T) {
	dir := t.TempDir()
	const relPath = "harbor-test.1"
	path := filepath.Join(dir, relPath)

	if err := os.WriteFile(path, []byte("original"), 0600); err != nil {
		t.Fatal(err)
	}

	root, err := os.OpenRoot(dir)
	if err != nil {
		t.Fatal(err)
	}
	defer root.Close()

	content, err := readManPage(root, relPath)
	if err != nil {
		t.Fatalf("readManPage() error = %v", err)
	}
	if string(content) != "original" {
		t.Fatalf("readManPage() = %q, want %q", content, "original")
	}

	if err := writeManPage(root, relPath, "updated"); err != nil {
		t.Fatalf("writeManPage() after readManPage() error = %v", err)
	}

	updated, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	if string(updated) != "updated" {
		t.Fatalf("updated content = %q, want %q", updated, "updated")
	}

	renameAndRemove(t, path)
}

func TestCleanManPagesClosesFilesAndIsIdempotent(t *testing.T) {
	dir := t.TempDir()
	path := filepath.Join(dir, "harbor-test.1")
	content := strings.Join([]string{
		`.TH "HARBOR" "1" "June 2026" "Harbor Community" "Harbor User Manuals"`,
		".SH NAME",
		`harbor-test \- test command`,
		".SH HISTORY",
		"generated by cobra",
		"",
	}, "\n")

	if err := os.WriteFile(path, []byte(content), 0600); err != nil {
		t.Fatal(err)
	}

	if err := cleanManPages(dir); err != nil {
		t.Fatalf("cleanManPages() error = %v", err)
	}
	cleaned, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}

	if err := cleanManPages(dir); err != nil {
		t.Fatalf("second cleanManPages() error = %v", err)
	}
	cleanedAgain, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	if string(cleanedAgain) != string(cleaned) {
		t.Fatalf("second clean changed content: got %q, want %q", cleanedAgain, cleaned)
	}

	cleanedText := string(cleaned)
	if strings.Contains(cleanedText, ".SH HISTORY") {
		t.Fatalf("cleaned content still contains HISTORY section: %q", cleanedText)
	}
	if strings.Contains(cleanedText, `"June 2026"`) {
		t.Fatalf("cleaned content still contains generated date: %q", cleanedText)
	}
	if strings.HasSuffix(cleanedText, "\n") {
		t.Fatalf("cleaned content has trailing newline: %q", cleanedText)
	}

	renameAndRemove(t, path)
}

func renameAndRemove(t *testing.T, path string) {
	t.Helper()

	renamed := path + ".renamed"
	if err := os.Rename(path, renamed); err != nil {
		t.Fatalf("rename after read/write cleanup: %v", err)
	}
	if err := os.Remove(renamed); err != nil {
		t.Fatalf("remove after read/write cleanup: %v", err)
	}
}
